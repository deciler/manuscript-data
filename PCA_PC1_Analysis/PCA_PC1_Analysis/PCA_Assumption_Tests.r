# 3. 定义计算函数 ----------------------------------------------
calc_kmo_bartlett <- function(data, group_name) {
  cat("\n", paste(rep("=", 60), collapse = ""), "\n")
  cat("【", group_name, "】\n")
  cat(paste(rep("-", 60), collapse = ""), "\n")
  
  # 处理Hg的0值（替换为最小正值的一半）
  for (j in 1:ncol(data)) {
    if (any(data[,j] == 0, na.rm = TRUE)) {
      min_pos <- min(data[data[,j] > 0, j], na.rm = TRUE)
      data[,j][data[,j] == 0] <- min_pos / 2
      cat("注意：", names(data)[j], "中有0值，已替换为", min_pos/2, "\n")
    }
  }
  
  # KMO检验
  kmo_result <- KMO(data)
  cat("\nKMO检验结果（各变量）:\n")
  print(round(kmo_result$MSA, 3))
  cat("\n整体KMO =", round(kmo_result$MSA[length(kmo_result$MSA)], 3), "\n")
  
  # Bartlett球形检验
  bartlett_result <- cortest.bartlett(cor(data), n = nrow(data))
  cat("\nBartlett球形检验:\n")
  cat("Chi-square =", round(bartlett_result$chisq, 2), 
      ", df =", bartlett_result$df, 
      ", p-value =", format(bartlett_result$p.value, scientific = TRUE, digits = 2), "\n")
  
  # 判断是否适合PCA
  kmo_value <- kmo_result$MSA[length(kmo_result$MSA)]
  if (kmo_value > 0.6 & bartlett_result$p.value < 0.05) {
    cat("\n>>> 判断：适合进行PCA ✓\n")
  } else {
    cat("\n>>> 判断：不适合进行PCA ✗\n")
  }
  
  # 返回结果
  return(data.frame(
    Group = group_name,
    n = nrow(data),
    KMO = round(kmo_value, 3),
    Bartlett_Chi2 = round(bartlett_result$chisq, 2),
    Bartlett_df = bartlett_result$df,
    Bartlett_p = format(bartlett_result$p.value, scientific = TRUE, digits = 2),
    Suitable = ifelse(kmo_value > 0.6 & bartlett_result$p.value < 0.05, "Yes", "No")
  ))
}

